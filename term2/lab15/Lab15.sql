-- 1. T_RANGE – диапазонное секционирование (NUMBER)
CREATE TABLE T_RANGE (
    ID        NUMBER       NOT NULL,
    DATA      VARCHAR2(100),
    CONSTRAINT T_RANGE_PK PRIMARY KEY (ID)
)
PARTITION BY RANGE (ID)
(
    PARTITION P_R_1   VALUES LESS THAN (100),
    PARTITION P_R_2   VALUES LESS THAN (200),
    PARTITION P_R_3   VALUES LESS THAN (MAXVALUE)
);


-- 2. T_INTERVAL – интервальное секционирование (DATE)
CREATE TABLE T_INTERVAL (
    ID        NUMBER       NOT NULL,
    CREATED   DATE         NOT NULL,
    DATA      VARCHAR2(100),
    CONSTRAINT T_INTERVAL_PK PRIMARY KEY (ID, CREATED)
)
PARTITION BY RANGE (CREATED)
INTERVAL ( NUMTOYMINTERVAL(1, 'MONTH') )  -- шаг 1 месяц
(
    PARTITION P_INT_START VALUES LESS THAN (DATE '2024-01-01')
);


-- 3. T_HASH – хэш-секционирование (VARCHAR2)
CREATE TABLE T_HASH (
    CODE      VARCHAR2(20) NOT NULL,
    DATA      VARCHAR2(100),
    CONSTRAINT T_HASH_PK PRIMARY KEY (CODE)
)
PARTITION BY HASH (CODE)
PARTITIONS 3;


-- 4. T_LIST – списочное секционирование (CHAR)
CREATE TABLE T_LIST (
    REGION    CHAR(2)      NOT NULL,
    DATA      VARCHAR2(100),
    CONSTRAINT T_LIST_PK PRIMARY KEY (REGION, DATA)
)
PARTITION BY LIST (REGION)
(
    PARTITION P_L_EU     VALUES ('EU'),
    PARTITION P_L_US     VALUES ('US'),
    PARTITION P_L_AS     VALUES ('AS'),
    PARTITION P_L_OTHERS VALUES (DEFAULT)
);


