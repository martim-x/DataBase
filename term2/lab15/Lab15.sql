-- 6. Перемещение строк между секциями при UPDATE ключа
-- 6.1 RANGE: ID из P_R_1 -> P_R_2
UPDATE T_RANGE
SET ID = 120
WHERE ID = 10;

-- проверка
SELECT ID, DATA FROM T_RANGE PARTITION (P_R_1);
SELECT ID, DATA FROM T_RANGE PARTITION (P_R_2);

-- 6.2 LIST: REGION из P_L_EU -> P_L_US
UPDATE T_LIST
SET REGION = 'US'
WHERE REGION = 'EU'
  AND DATA = 'row eu 1';

-- проверка
SELECT REGION, DATA FROM T_LIST PARTITION (P_L_EU);
SELECT REGION, DATA FROM T_LIST PARTITION (P_L_US);

COMMIT;


