-- 9. ALTER TABLE ... EXCHANGE для одной таблицы (T_LIST)
CREATE TABLE T_LIST_STG (
    REGION    CHAR(2)      NOT NULL,
    DATA      VARCHAR2(100),
    CONSTRAINT T_LIST_STG_PK PRIMARY KEY (REGION, DATA)
);

INSERT INTO T_LIST_STG VALUES ('EU', 'stg eu 1');
INSERT INTO T_LIST_STG VALUES ('EU', 'stg eu 2');
COMMIT;

ALTER TABLE T_LIST
EXCHANGE PARTITION P_L_EU
WITH TABLE T_LIST_STG
WITHOUT VALIDATION;

-- проверка: что теперь в P_L_EU и в T_LIST_STG
SELECT REGION, DATA, 'P_L_EU' AS SRC
FROM   T_LIST PARTITION (P_L_EU);

SELECT REGION, DATA, 'T_LIST_STG' AS SRC
FROM   T_LIST_STG;


